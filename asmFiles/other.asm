# ============================================================
# U-Type
# ============================================================
lui $10, 10
sw $10, 0($0)

auipc $11, 12
sw $11, 4($0)

# ============================================================
# I-Type
# ============================================================
li $26, 4
addi $12, $26, 1
sw $12, 8($0) #expected: 5

li $16, 10
xori $13, $16, 12
sw $13, 12($0) #0b1010 XOR 0b1100 = 0b0110 = 6

li $16, 10
ori $12, $16, 12
sw $12, 16($0) # 0b1010 OR 0b1100 = 0b1110 = 14

# ============================================================
# Other
# ============================================================
li $8, 3
slli $5, $8, 3
sw $5, 20($0) # expected: 3 << 3 = 24

li $7, -16
srli $8, $7, 1
sw $8, 24($0)
# -16 = 0xFFFFFFF0
# logical >> 1 = 0x7FFFFFF8

srai $6, $7, 1
sw $6, 28($0)
# arithmetic >> 1 = 0xFFFFFFF8 = -8

li $7, -1
slti $8, $7, 2
sw $8, 32($0)
# signed: -1 < 2 -> 1

sltiu $3, $7, 2
sw $3, 36($0)
# unsigned: 0xFFFFFFFF < 2 -> 0

li $8, -1
li $5, 2
sltu $3, $8, $5
sw $3, 40($0)
# unsigned: 0xFFFFFFFF < 2 -> 0

sltu $3, $5, $8
sw $3, 44($0)
# unsigned: 2 < 0xFFFFFFFF -> 1

# ============================================================
# R-Type Logic
# ============================================================
li $4, 10 # 1010
li $5, 12 # 1100
xor $3, $4, $5
sw $3, 48($0) # expected: 0110 = 6

or $3, $4, $5
sw $3, 52($0) # expected: 1110 = 14
halt
